const fs = require('node:fs');
const assert = require('node:assert/strict');
const config = JSON.parse(fs.readFileSync('vercel.json','utf8'));
const page = fs.readFileSync('login.html','utf8');
const js = fs.readFileSync('client-access.js','utf8');
assert.ok(config.rewrites.some(r=>r.source==='/'&&r.destination==='/login.html'),'Root must be login-first');
for (const id of ['loginForm','clientPanel','entryShell','signOut','workspace','leadForm','signInTab','signUpTab']) assert.match(page,new RegExp('id="'+id+'"'));
assert.match(page,/href="index\.html"/,'Guest route must lead to public pages');
assert.match(js,/API='https:\/\/matrix360-crm-backend-p9os\.onrender\.com'/);
assert.match(js,/let token=null,workspace=null,memberships=\[\],stages=\[\],version=0,authVersion=0/);
assert.match(js,/function signOut\(\)\{\+\+authVersion;\+\+version;token=null/);
assert.match(js,/const attempt=\+\+authVersion/);
assert.ok((js.match(/if\(attempt!==authVersion\)return/g)||[]).length>=3,'Pending login must be invalidated at each asynchronous boundary');
assert.match(js,/if\(!Array\.isArray\(ms\)\|\|ms\.length===0\)throw Error/);
assert.match(js,/if\(res\.status===401&&token\)\{signOut\(\)/);
assert.doesNotMatch(js.replace(/\/\*[\s\S]*?\*\//g,''),/\blocalStorage\s*\./);
assert.doesNotMatch(js,/\bsessionStorage\s*\./);
assert.doesNotMatch(js,/\binnerHTML\s*=/,'Untrusted CRM values must not be HTML');
assert.match(js,/document\.createElement\('td'\)/);
console.log('Gateway routing, session and tenant-boundary source checks passed. Browser E2E remains separate.');
