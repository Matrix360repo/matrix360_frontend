const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('login.html','utf8');
const js=fs.readFileSync('client-access.js','utf8');
const dom=new JSDOM(html,{url:'https://matrix360frontend-test.example/login.html',runScripts:'outside-only'});
const w=dom.window,doc=w.document;
w.HTMLElement.prototype.scrollIntoView=function(){};
const calls=[];
let leads=[{id:1,name:'Synthetic lead',source:'fixture',stage:'enquiry'}];
const response=(status,body)=>({ok:status>=200&&status<300,status,async json(){return body}});
w.fetch=async (url,options={})=>{
 const u=new URL(url),path=u.pathname,method=options.method||'GET';
 calls.push({path,method,headers:options.headers||{}});
 if(path==='/auth/login')return response(200,{access_token:'synthetic-token'});
 if(path==='/me/workspaces')return response(200,[{id:'lakhotia',name:'Lakhotia',role:'client_admin'}]);
 if(path==='/workspaces/lakhotia/stages')return response(200,['enquiry','qualified']);
 if(path==='/workspaces/lakhotia/channel-status')return response(200,{workspace_id:'lakhotia',crm:{status:'connected'},channels:{whatsapp:{status:'not_connected'},instagram:{status:'not_connected'},email:{status:'not_connected'}}});
 if(path==='/workspaces/lakhotia/leads'&&method==='GET')return response(200,leads);
 if(path==='/workspaces/lakhotia/leads/1'&&method==='PATCH'){leads=[{...leads[0],stage:JSON.parse(options.body).stage}];return response(200,{ok:true});}
 if(path==='/auth/logout')return response(200,{ok:true});
 return response(404,{detail:'Unexpected synthetic fixture request'});
};
w.eval(js);
const wait=()=>new Promise(resolve=>setTimeout(resolve,25));
(async()=>{
 doc.getElementById('userName').value='fixture@example.com';
 doc.getElementById('password').value='synthetic-password';
 doc.getElementById('loginForm').dispatchEvent(new w.Event('submit',{cancelable:true,bubbles:true}));
 await wait();
 assert.ok(doc.body.classList.contains('authed'),'Approved test user should see private workspace');
 assert.equal(doc.querySelectorAll('#leadRows tr').length,1,'CRM records must render');
 assert.ok(calls.some(x=>x.path==='/workspaces/lakhotia/channel-status'),'Frontend must fetch real backend status contract');
 doc.getElementById('assistantQuestion').value='How are my WhatsApp campaigns doing?';
 doc.getElementById('assistantForm').dispatchEvent(new w.Event('submit',{cancelable:true}));
 assert.match(doc.getElementById('assistantAnswer').textContent,/not currently available/);
 const select=doc.querySelector('#leadRows select');
 select.value='qualified';
 select.dispatchEvent(new w.Event('change',{bubbles:true}));
 await wait();
 assert.equal(leads[0].stage,'qualified');
 assert.ok(calls.some(x=>x.path==='/workspaces/lakhotia/leads/1'&&x.method==='PATCH'));
 doc.getElementById('signOut').click();
 await wait();
 assert.ok(!doc.body.classList.contains('authed'));
 assert.equal(doc.querySelectorAll('#leadRows tr').length,0,'Logout clears private DOM');
 console.log('PASS: synthetic login -> tenant workspace -> live CRM contract mock -> lead stage update -> logout');
 dom.window.close();
})().catch(e=>{console.error(e);process.exitCode=1;dom.window.close()});
